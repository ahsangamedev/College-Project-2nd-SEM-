namespace SnakeGameFinal
{
    // Direction - Enum representing the four cardinal directions the snake can move on the 2D grid.
    public enum Direction
    {
        Up,     // Moves toward decreasing Y (top of screen)
        Down,   // Moves toward increasing Y (bottom of screen)
        Left,   // Moves toward decreasing X (left of screen)
        Right   // Moves toward increasing X (right of screen)
    }
}
